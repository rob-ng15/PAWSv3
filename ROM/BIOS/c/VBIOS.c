void reset_system( void ) {
    for( int channel = 0; channel < 6; channel++) beep_stop( channel );
    for( int i = 0; i < 6; i++ ) AUDIO_DURATION[ i ] = 0;

    *GPU_DITHERMODE = 0;
    *CROP_LEFT = 0; *CROP_RIGHT = 319; *CROP_TOP = 0; *CROP_BOTTOM = 239;
    *FRAMEBUFFER_DRAW = 3; gpu_cs(); while( !*GPU_FINISHED );
    *FRAMEBUFFER_DRAW = 1; *BITMAP_DISPLAY256 = 0;
    *SCREENORDER = ( 3 << 0 ) | ( 1 << 4 ) | ( 4 << 8 ) | ( 8 << 12 ) | ( 9 << 16 ) | ( 10 << 20 ) | ( 11 << 24 );
    *COLOUR = 0;
    tpu_cs(); *TPU_LOREZ = 0; *TPU_CURSOR = 1;
    *TM_LOREZ = 0;
    for( int i = 0; i < 4; i++ ) {
        tm_cs( i );
    }
    for( int i = 0; i < 63; i++ ) SPRITE_ACTIVE[i] = 0;
}

void timer_interrupt( void ) {
    tpu_set( 0, 17, TRANSPARENT, WHITE, 1 );
    long rtc = *RTC + 0x2000000000000000;
    for( int i = 0; i < 16; i++ ) {
        rtc = _rv64_rol( rtc, 4 );
        switch(i) {
            case 8: case 9: break;
            default: tpu_output_character( 48 + ( rtc & 0xf ) );
        }
        switch(i) {
            case 3: case 5: tpu_output_character('-'); break;
            case 7: tpu_output_character(' '); break;
            case 11: case 13: tpu_output_character(':'); break;
        }
    }
}

void vblank_interrupt( void ) {
    static int j = 0;

    tilemap_scroll( 0, 3, 1 );
    tilemap_scroll( 1, 1, 1 );
    tilemap_scroll( 2, 1, 1 );
    tilemap_scroll( 3, 3, 1 );
    update_sprite( 0, 0, 1, 0, 0 ); update_sprite( 2, 0, 1, 0, 0 );
    set_sprite_attribute( 0, 1, ( ( j & 192 ) >> 6 ) );
    set_sprite_attribute( 2, 1, ( j & 128 ) >> 7 );
    j++;
}

typedef struct{
    float x,y;
} complex;

complex add( complex a, complex b ) {
    complex c;
    c.x = a.x + b.x;
    c.y = a.y + b.y;
    return c;
}

complex sqr(complex a){
    complex c;
    c.x = a.x*a.x - a.y*a.y;
    c.y = 2*a.x*a.y;
    return c;
}

float sqrt(float x) {
    float result;
    // fsqrt.s <destination_reg>, <source_reg>
    asm ("fsqrt.s %0, %1" : "=f" (result) : "f" (x));
    return result;
}

float mod(complex a){
    return sqrt(a.x*a.x + a.y*a.y);
}

complex mapPoint(int width,int height,float radius,int x,int y,float scale){
    complex c;
    int l = (width<height)?width:height;

    c.x = 2*radius*(x - width/2.0)/scale;
    c.y = 2*radius*(y - height/2.0)/scale;

    return c;
}

void juliaSet(int width,int height,int y_start, complex c,float radius,int n,float scale){
    int x,y,i;
    complex z0,z1;

    for(x=0;x<=width;x++)
        for(y=0;y<=height;y++){
            z0 = mapPoint(width,height,radius,x,y,scale);
            for(i=1;i<=n;i++){
                z1 = add(sqr(z0),c);
                if(mod(z1)>radius){
                    gpu_pixel(i,x,y+y_start);
                    break;
                }
                z0 = z1;
            }
        }
}

